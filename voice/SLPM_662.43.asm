; 银河天使2 绝对领域之门：普通战斗语音文本框补丁
;
; 设计目标：复用游戏原生语音回调中的头像/文本框流程。
; 本补丁只在普通战斗 state 0 激活文本框，并关闭光标/等待状态。
; 语音播放、头像创建、3D流程、语音结束关闭均交给原程序。
;
; 本作关键地址：
;   0x164C90 = sub_164C90，语音状态回调
;   0x164D84 = state 0 的文本显示分支入口（跳板覆盖点）
;   0x1127A8 = 代码洞，存放补丁逻辑
;
; 本作场景/UI地址：
;   [0x2CCA6C]       当前场景指针
;   scene + 0x828    战斗文本/头像 UI 对象
;   object + 0x168   +360，文本框激活标志：1=激活，0=关闭
;   object + 0x174   +372，光标/等待处理开关：0=普通文本，非0=教学/选项状态
;
; 注意：+372 属于共享文本对象状态，因此本版本选择统一设为 0。
; 这会让教学对话的点击按钮也不显示，但逻辑最短、最稳定。
; 若续作地址变化，只需重新定位上述地址和对象偏移。
;
;==============================================================================
; 换行机制研究结论（IDA 逆向确认）：
;   sub_1CE0A0 (0x1CE0A0) = 文本解析器，把原始字符串解析进排版缓冲区：
;     - 0x0A  : 换行符，作为特殊字符存入缓冲区（0x1CE0F8 处特判）
;     - 0x00  : 字符串结束
;     - \s##  : 打字机速度（两位十进制）
;     - \v#   : 逐字间隔
;     - \c####: 颜色（十六进制 RGBA）
;     - \ + 其他字符 : 字面反斜杠（即 "\n" 不是转义，会原样显示 "\n"）
;   sub_111C70 (0x111E50) = 字形渲染循环：
;     - 遇到字符 10 → 行高累加、x 重置，实现换行
;     - 行宽测量循环遇到 10 也提前结束
;   结论：游戏只认真换行符 0x0A，没有自动折行，也不认识字面 "\n"。
;
;   因此本补丁在文本播放前（ActivateBattleBox 跳板内、s3 尚未被消费时）
;   把字面 "\n"(5C 6E) 原地压缩转换为 0x0A。原地转换只会缩短字符串，
;   且幂等（重复转换无副作用）。双字节字符按解析器同款 lead 判定
;   (0x81-0x9F / 0xE0-0xEF) 整对拷贝，避免尾字节 0x5C + 'n' 误判。
;==============================================================================
.ps2
.open "SLPM_662.43", "out\SLPM_662.43", 0xFF000
.org 0x164D84
; 覆盖原 state 0 分支的两条指令，转入代码洞。
; 返回时必须补回原来的 lw v0, [0x2CCA6C]，否则文本不会显示。
  j ActivateBattleBox
  nop
.org 0x1127A8
ActivateBattleBox:
; s3 是原生 state 0 传入的文本指针；为空则保持原流程。
  beqz s3, @@no_text
  nop
  lui t0, 0x2D
  lw t0, -0x3594(t0)
  beqz t0, @@resume
  nop
  lw t1, 0x828(t0)
  beqz t1, @@resume
  nop
; 激活常驻文本框，并统一关闭光标/等待按钮状态。
  addiu t2, zero, 1
  sw t2, 0x168(t1)
  sw zero, 0x174(t1)
; --- 把字面 "\n" (5C 6E) 原地压缩为真换行符 0A ---
; s3 指向的文本位于可写 RAM，转换后 src/dst 同地址，下游
; (sub_16CC78 解析 / sub_16CB08 逐字机 / 渲染) 全部使用转换结果。
  or a0, s3, zero       ; src
  or a1, s3, zero       ; dst，恒有 dst <= src，原地安全
@@cv_loop:
  lbu t0, 0(a0)
  beqz t0, @@cv_done    ; 字符串结束
  addiu t1, t0, -0x81
  sltiu t1, t1, 0x1F    ; lead 0x81-0x9F ?
  bnez t1, @@cv_pair
  addiu t1, t0, -0xE0
  sltiu t1, t1, 0x1D    ; lead 0xE0-0xEF ?
  bnez t1, @@cv_pair
  nop
  addiu t1, zero, 0x5C  ; '\' ?
  bne t0, t1, @@cv_copy
  addiu t1, zero, 0x6E  ; 'n' ?
  lbu t2, 1(a0)
  bne t2, t1, @@cv_copy
  nop
  addiu t0, zero, 0x0A  ; "\n" → 0x0A
  addiu a0, a0, 2
  sb t0, 0(a1)
  addiu a1, a1, 1
  b @@cv_loop
  nop
@@cv_pair:              ; 双字节字符整对拷贝，不拆开判断
  sb t0, 0(a1)
  lbu t0, 1(a0)
  sb t0, 1(a1)
  addiu a0, a0, 2
  addiu a1, a1, 2
  b @@cv_loop
  nop
@@cv_copy:              ; 单字节原样拷贝（无 "\n" 时等于原串重写，幂等）
  sb t0, 0(a1)
  addiu a0, a0, 1
  addiu a1, a1, 1
  b @@cv_loop
  nop
@@cv_done:
  sb zero, 0(a1)        ; 补写结束符：发生过压缩时 dst 位置残留旧串尾巴，
                        ; 不补 0x00 解析器会越界读到垃圾（末尾乱码根因）
@@resume:
; 补回被覆盖的原指令：lw v0, dword_2CCA6C。
  lui t0, 0x2D
  lw v0, -0x3594(t0)
  j 0x164D8C
  nop
@@no_text:
  j 0x164D98
  nop

;==============================================================================
; 3D模式头像显示补丁（只加不改原逻辑）
;
; 原因: 3D观察模式(模式3/4/5)下, 游戏有两处主动隐藏头像:
;   ① sub_19F1C8 +0x19F2B0: 创建头像时 show=0 (不显示)
;   ② sub_19EEB8 +0x19EFFC: 每帧循环强制 hide(头像, 0)
; 只改①不改② → 头像闪一帧就被每帧循环杀掉
; 只改②不改① → 头像根本不创建
; 两处都改成"用配置值(s2)"才能让3D模式显示头像
;==============================================================================

; ① 创建时: 0x19F2B0 的 move $s0,$zero 改为 move $s0,$s2
;    文件偏移 0xF02B0, 原字节 00 00 08 24, 改为 48 02 00 25
.org 0x19F2B0
  or    $s0, $s2, $zero      ; 3D模式也用配置值(显示头像), 原为 addiu $s0,$zero,0

; ② 每帧循环: 0x19EFFC 的 move $a1,$zero 改为 move $a1,$s2
;    文件偏移 0xEFFFC, 原字节 00 00 04 24, 改为 48 02 04 25
.org 0x19EFFC
  or    $a1, $s2, $zero      ; 3D模式每帧保持可见, 原为 addiu $a1,$zero,0

.close
